import json
import os
from functools import lru_cache
from pathlib import Path

import joblib


ARTIFACT_DIR = Path(__file__).resolve().parents[2] / "artifacts"

SUPPORTED_MODELS = {
    "logistic_regression",
    "xgboost",
}


@lru_cache(maxsize=2)
def load_model(name: str):
    if name not in SUPPORTED_MODELS:
        raise ValueError(f"Unsupported model: {name}")

    model_path = ARTIFACT_DIR / f"{name}.joblib"
    metrics_path = ARTIFACT_DIR / f"{name}_metrics.json"

    if not model_path.exists() or not metrics_path.exists():
        raise FileNotFoundError(
            f"Missing model or metrics for {name}. Train it first."
        )

    # Only load artifacts generated by your own training scripts.
    model = joblib.load(model_path)

    report = json.loads(
        metrics_path.read_text(encoding="utf-8")
    )

    threshold = float(report["validation"]["threshold"])

    return model, threshold, report


def load_active_model():
    name = os.getenv(
        "ACTIVE_MODEL",
        "logistic_regression",
    )

    model, threshold, report = load_model(name)

    return {
        "name": name,
        "model": model,
        "threshold": threshold,
        "report": report,
    }